  /// The full list for the current data.
  static List<String> build(FinanceData data) {
    final words = <String>{};
    void add(String text) {
      for (final w
          in text
              .toLowerCase()
              .replaceAll('ё', 'е')
              .split(RegExp(r'[^а-яa-z]+'))) {
        if (w.length >= 2 && RegExp(r'[а-я]').hasMatch(w)) words.add(w);
      }
    }

    add(_base);
    for (final c in data.categories) {
      if (!c.archived) add(c.name);
    }
    for (final a in data.accounts) {
      if (!a.archived) add(a.name);
    }
    for (final g in data.goals) {
      add(g.name);
    }
    for (final s in [...ServiceCatalog.entries, ...StoreCatalog.entries]) {
      add(s.name);
      for (final alias in s.aliases) {
        add(alias);
      }
    }
    return words.toList()..sort();
  }
