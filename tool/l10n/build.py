"""Builds lib/presentation/l10n_table.dart from keys.txt and t*.txt.

keys.txt: one Russian UI string per line (\\n for a line break, {1}… for the
inserted values). t*.txt: `N¦en¦es¦pt¦fr¦de¦zh¦hi¦ar` (N — line in keys.txt)
or `=Russian¦en¦…` for a key written out.
"""
import glob, os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
langs = ['en', 'es', 'pt', 'fr', 'de', 'zh', 'hi', 'ar']
keys = open(os.path.join(here, 'keys.txt'), encoding='utf-8').read().split('\n')
table = {}
bad = 0
for path in sorted(glob.glob(os.path.join(here, 't*.txt'))):
    for n, line in enumerate(open(path, encoding='utf-8').read().split('\n'), 1):
        if not line.strip():
            continue
        parts = line.split('¦')
        if len(parts) != 9:
            print(f'{path}:{n}: {len(parts)} columns', file=sys.stderr); bad += 1; continue
        key = parts[0][1:] if parts[0].startswith('=') else keys[int(parts[0]) - 1]
        holes = sorted(set(__import__('re').findall(r'\{\d\}', key)))
        for lang, value in zip(langs, parts[1:]):
            if sorted(set(__import__('re').findall(r'\{\d\}', value))) != holes:
                print(f'{path}:{n}: {lang} placeholders differ', file=sys.stderr); bad += 1
        table[key] = parts[1:]
def q(s):
    s = s.replace('\\', '\\\\').replace('\\\\n', '\\n')
    return "'" + s.replace("'", "\\'").replace('$', '\\$') + "'"
out = ['// Generated by tool/l10n/build.py — do not edit by hand.', '',
       '/// Languages after Russian, in the order of [l10nTable] values.',
       'const l10nLanguages = [' + ', '.join(q(l) for l in langs) + '];', '',
       '/// Russian UI line → its translations ({1}, {2}… are inserted values).',
       'const l10nTable = <String, List<String>>{']
for key, values in table.items():
    out.append(f'  {q(key)}: [' + ', '.join(q(v) for v in values) + '],')
out.append('};')
open(os.path.join(root, 'lib/presentation/l10n_table.dart'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(table), 'keys,', bad, 'problems')
